/// 経度 0〜360 の表記を −180〜180 に
double _lon(double lon) => lon > 180 ? lon - 360 : lon;

void main() {
  group('WMM2025 公式検算値', () {
    for (final (name, rows) in [('TestValues 100 点', _official100), ('技術報告 12 点', _report12)]) {
      test(name, () {
        for (final (year, alt, lat, lon, decl) in rows) {
          final got = WmmDeclination.atDecimalYear(lat, _lon(lon), year, altitudeKm: alt);
          expect(got, closeTo(decl, 0.01), reason: '$year ${alt}km $lat,$lon');
        }
      });
    }
  });

  group('北山村（33.93N 135.96E）', () {
    test('NOAA の計算機と一致する（2026.8 で −7.87666°）', () {
      // https://www.ngdc.noaa.gov/geomag-web/calculators/calculateDeclination?lat1=33.93&lon1=135.96&model=WMM&startYear=2026&startMonth=10&startDay=20&resultFormat=json
      // を 2026-10-11 に引いた値（model WMM-2025, date 2026.8, elevation 0）
      expect(WmmDeclination.atDecimalYear(33.93, 135.96, 2026.8), closeTo(-7.87666, 0.01));
    });

    test('国土地理院の偏角一覧（2020.0 年値）と大きくは違わない', () {
      // https://www.gsi.go.jp/common/000237031.txt の 33.9583 135.9375（二次メッシュ 503577）は 西偏 7°30′。
      // 年代（2020.0 と 2026.8）・地殻の局所異常の扱い・10′ 丸めが違うので、ずれは 0.5° 以内であればよい
      expect(WmmDeclination.atDecimalYear(33.9583, 135.9375, 2026.8), closeTo(-7.5, 0.5));
    });

    test('DateTime からも同じ値（2026-10-20 ≒ 2026.8）', () {
      expect(WmmDeclination.decimalYear(DateTime(2026, 10, 20)), closeTo(2026.8, 0.001));
      expect(WmmDeclination.calculate(33.93, 135.96, DateTime(2026, 10, 20)), closeTo(-7.87666, 0.01));
    });
  });

  group('真北への直し', () {
    test('偏角を足して 0〜360 に収める', () {
      expect(magneticToTrue(0, -7.88), closeTo(352.12, 1e-9));
      expect(magneticToTrue(359, 3), closeTo(2, 1e-9));
      expect(magneticToTrue(90, -7.88), closeTo(82.12, 1e-9));
    });

    test('北山村で磁北 0° を向いた端末は真北基準で 352.1° 付近', () {
      final conv = TrueHeadingConverter(clock: () => DateTime(2026, 10, 20));
      expect(conv.toTrue(0, lat: 33.93, lon: 135.96), closeTo(360 - 7.87666, 0.01));
    });

    test('位置がまだ分からなければ直さない。一度分かればその偏角を使い続ける', () {
      final conv = TrueHeadingConverter(clock: () => DateTime(2026, 10, 20));
      expect(conv.toTrue(10), 10);
      conv.toTrue(10, lat: 33.93, lon: 135.96);
      expect(conv.toTrue(10), closeTo(10 - 7.87666, 0.01));
    });

    test('近くを動いただけでは出し直さず、遠くへ行けば出し直す', () {
      final conv = TrueHeadingConverter(clock: () => DateTime(2026, 10, 20));
      final kitayama = conv.declinationFor(33.93, 135.96)!;
      expect(conv.declinationFor(33.95, 135.97), kitayama);
      // 北海道（稚内付近）は西偏 10° 近い
      final wakkanai = conv.declinationFor(45.4, 141.7)!;
      expect(wakkanai, lessThan(kitayama - 1));
      expect(wakkanai, closeTo(WmmDeclination.calculate(45.4, 141.7, DateTime(2026, 10, 20)), 1e-12));
    });
  });
}
